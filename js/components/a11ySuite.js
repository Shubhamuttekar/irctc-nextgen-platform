export class A11ySuite {
  constructor() {
    this.currentFontScale = localStorage.getItem('irctc_font_scale') || 'md';
    this.isHighContrast = localStorage.getItem('irctc_high_contrast') === 'true';
    this.currentLang = localStorage.getItem('irctc_lang') || 'en';

    this.init();
  }

  init() {
    this.applyFontScale(this.currentFontScale);
    this.applyContrast(this.isHighContrast);
    this.applyLanguage(this.currentLang);
    this.bindEvents();
  }

  applyFontScale(scale) {
    this.currentFontScale = scale;
    document.documentElement.setAttribute('data-font-size', scale);
    localStorage.setItem('irctc_font_scale', scale);

    const fontButtons = document.querySelectorAll('.btn-font-scale');
    fontButtons.forEach((btn) => {
      btn.classList.toggle('active', btn.dataset.scale === scale);
    });
  }

  applyContrast(isHigh) {
    this.isHighContrast = isHigh;
    if (isHigh) {
      document.documentElement.setAttribute('data-contrast', 'high');
    } else {
      document.documentElement.removeAttribute('data-contrast');
    }
    localStorage.setItem('irctc_high_contrast', String(isHigh));

    const toggleBtn = document.getElementById('btn-toggle-contrast');
    if (toggleBtn) {
      toggleBtn.classList.toggle('active', isHigh);
      toggleBtn.setAttribute('aria-pressed', String(isHigh));
    }
  }

  applyLanguage(langCode) {
    this.currentLang = langCode;
    const dict = TRANSLATIONS[langCode] || TRANSLATIONS.en;
    localStorage.setItem('irctc_lang', langCode);

    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    const langSelect = document.getElementById('select-language');
    if (langSelect) {
      langSelect.value = langCode;
    }

    // Broadcast language change to components
    window.dispatchEvent(new CustomEvent('irctc-language-change', { detail: { lang: langCode, dict } }));
  }

  bindEvents() {
    // Font scale buttons
    document.querySelectorAll('.btn-font-scale').forEach((btn) => {
      btn.addEventListener('click', () => {
        this.applyFontScale(btn.dataset.scale);
      });
    });

    // Contrast toggle button
    const contrastBtn = document.getElementById('btn-toggle-contrast');
    if (contrastBtn) {
      contrastBtn.addEventListener('click', () => {
        this.applyContrast(!this.isHighContrast);
      });
    }

    // Language dropdown selector
    const langSelect = document.getElementById('select-language');
    if (langSelect) {
      langSelect.addEventListener('change', (e) => {
        this.applyLanguage(e.target.value);
      });
    }
  }
}
